import { describe, expect, it } from 'vitest';

import { isReadonlyBash } from '#/utils/readonly-bash';

describe('isReadonlyBash', () => {
  it.each([
    'cd /tmp',
    'echo hello',
    'printf "%s\\n" hello',
    'sleep 1',
    'true',
    'test -f package.json',
    'cat package.json',
    'head -n 20 package.json',
    'tail -f log.txt',
    'wc -l package.json',
    'file package.json',
    'stat package.json',
    'ls -la',
    'tree -L 2',
    'which node',
    'diff old.ts new.ts',
    'jq . package.json',
    'cut -d, -f1 data.csv',
    'tr a-z A-Z',
    'nl package.json',
    'column -t data.csv',
    'sort -u input.txt',
    'uniq input.txt',
    'date',
    'date +%s',
    'date -u +%F',
    'date -d yesterday +%F',
    'date -j -f %s 0 +%F',
    'xxd input.txt',
    'rg "needle" src',
    'grep -R "needle" src',
    "sed -n '10,20p' input.txt",
    "sed --quiet -e '1,2p' -e '4p' input.txt",
    "find . -name '*.ts' -print",
    'git status --short',
    'git -C /tmp/repo log -1',
    'git --no-pager show HEAD',
    'git diff HEAD~1',
    'git rev-parse HEAD',
    'git ls-files',
    'git blame file.ts',
    'git merge-base main HEAD',
    'git describe --tags',
    'git rev-list --count HEAD',
    'git branch --show-current',
    'git branch --list --all',
    'git tag --list',
    'git remote -v',
    'git remote show origin',
    'git remote get-url origin',
    'git stash list',
    'git stash show -p',
    'git worktree list',
    'git config --get user.name',
    'git config --list',
    'gh pr view 123',
    'gh pr list',
    'gh pr diff 123',
    'gh pr checks 123',
    'gh pr status',
    'gh issue view 123',
    'gh issue list',
    'gh run view 123',
    'gh run list',
    'gh run watch 123',
    'gh repo view',
    'gh api repos/example/example',
    'gh api repos/example/example -X GET',
    'ls >/dev/null 2>&1',
    'ls 2>/dev/null',
    'ls &>/dev/null',
    'cat < input.txt',
    'true <> /dev/null',
    'true 3<> /dev/null',
    'printf hello | jq .',
    'for file in *.ts; do cat "$file"; done',
    'cat "$(printf hello)"',
    'cat <(printf hello)',
    'LC_ALL=C sort a.txt',
    'LANG=en_US.UTF-8 jq . package.json',
    'TZ=UTC date',
    'NO_COLOR=1 rg needle src',
    'FORCE_COLOR=0 grep needle src',
    'CLICOLOR=0 ls',
    'TERM=dumb file package.json',
    'COLUMNS=100 LINES=40 ls',
    'PAGER=cat GIT_PAGER=cat git log',
    'while read -r line; do printf "%s" "$line"; done < input.txt',
  ])('allows %s', (command) => {
    expect(isReadonlyBash(command)).toBe(true);
  });

  it.each([
    'echo hello > output.txt',
    'cat input.txt >> output.txt',
    'printf hello | tee output.txt',
    'tee output.txt',
    'ls 2>errors.txt',
    'ls &>output.txt',
    'true <> created-by-diamond.txt',
    'echo hi <> created-by-echo-diamond.txt',
    'true 3<> created-by-fd-diamond.txt',
    'sort -o output.txt input.txt',
    'sort -ocreated-by-sort-attached.txt input.txt',
    'sort -uo output.txt input.txt',
    'sort --output=output.txt input.txt',
    'sort --compress-program=./compress.sh input.txt',
    'tree -o output.txt',
    'tree -ao output.txt',
    'file -C -m magic',
    'file --compile -m magic.src',
    'sed -ni \'1p\' notes.txt',
    'sed -nEi \'1p\' notes.txt',
    'sed -in \'1p\' notes.txt',
    'uniq input.txt output.txt',
    'date 010100002026',
    'date -f %s 0',
    'date -s tomorrow',
    'date -s 2020-01-01',
    'date --set=x',
    'xxd -r input.txt output.txt',
    'xxd input.txt output.txt',
    'rg --pre ./preprocess.sh needle src',
    'rg --pre=./preprocess.sh needle src',
    "sed -n 'w output.txt' input.txt",
    "sed -n '1w output.txt' input.txt",
    'sed -i s/a/b/ input.txt',
    "sed -n -f commands.sed input.txt",
    "sed -n '1e echo unsafe' input.txt",
    'find . -exec rm {} \\;',
    'find . -execdir rm {} \\;',
    'find . -ok rm {} \\;',
    'find . -okdir rm {} \\;',
    'find . -delete',
    'find . -fprint output.txt',
    'find . -fprint0 output.txt',
    'find . -fprintf output.txt %p',
    'find . -fls output.txt',
    'GIT_EXTERNAL_DIFF=./x.sh git diff',
    'PAGER=./x.sh git log',
    'GIT_PAGER=./x.sh git log',
    'GIT_SSH_COMMAND=./x.sh git ls-files',
    'LESSOPEN=|./x.sh git diff',
    'EDITOR=./x.sh git show',
    'git -c color.ui=always status',
    'git log --output=history.txt',
    'git diff --output patch.txt',
    'git log -1 -p --ext-diff',
    'git show --ext-diff HEAD',
    'git diff --textconv',
    'git grep -O./driver.sh world',
    'git grep --open-files-in-pager=./pager.sh world',
    'git commit -m change',
    'git branch new-branch',
    'git tag v1.0.0',
    'git remote remove origin',
    'git stash pop',
    'git worktree add /tmp/worktree',
    'git config user.name example',
    'gh api repos/example/example/issues -f title=change',
    'gh api repos/example/example/issues -F title=change',
    'gh api repos/example/example/issues -ftitle=hidden',
    'gh api repos/example/example/issues -Fbody=hidden',
    'gh api repos/example/example/issues --field title=change',
    'gh api repos/example/example/issues --input payload.json',
    'gh api repos/example/example -X POST',
    'gh api repos/example/example --method=DELETE',
    'gh api graphql -f query="{ viewer { login } }"',
    'gh pr merge 123',
    'gh issue close 123',
    'printf hello | rm -f output.txt',
    'cat "$(rm -f output.txt)"',
    'cat <(rm -f output.txt)',
    'for file in *.ts; do rm "$file"; done',
    'printf hello | tee /dev/null',
    'rm -f output.txt',
    'ls "',
  ])('rejects %s', (command) => {
    expect(isReadonlyBash(command)).toBe(false);
  });

  it('rejects a parse that exceeds the node budget', () => {
    expect(isReadonlyBash('true; '.repeat(20_001))).toBe(false);
  });

  it('rejects input with no executable command', () => {
    expect(isReadonlyBash('ANSWER=42')).toBe(false);
  });
});
